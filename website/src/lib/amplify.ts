const MODELS = (outputs as { data?: { model_introspection?: { models?: Record<string, { fields?: Record<string, unknown> }> } } }).data?.model_introspection?.models;

/**
 * True when the deployed backend has this field. Lets a newer website run on an
 * older backend: form boxes for fields the backend does not have yet are hidden.
 */
export function hasField(model: string, field: string): boolean {
  const m = MODELS?.[model];
  return !m?.fields || field in m.fields;
}

/** Drops keys the deployed backend does not know, so saving never fails on a newer form. */
export function fit<T extends Record<string, unknown>>(model: string, input: T): T {
  return Object.fromEntries(Object.entries(input).filter(([k]) => hasField(model, k))) as T;
}

/** True when amplify_outputs.json has been generated by a real deployment. */
export const isConfigured = Boolean((outputs as { data?: unknown }).data);

type ListResult = { data: unknown[]; nextToken?: string | null; errors?: { message: string }[] };

/** Fetches every item of a model, following pagination. */
export async function listAll<T>(model: unknown, extra: Record<string, unknown> = {}): Promise<T[]> {
  const m = model as { list: (o: Record<string, unknown>) => Promise<ListResult> };
  const items: T[] = [];
  let nextToken: string | null | undefined;
  do {
    const res = await m.list({ limit: 1000, nextToken, ...extra });
    if (res.errors?.length) throw new Error(res.errors.map((e) => e.message).join('; '));
    items.push(...(res.data.filter(Boolean) as T[]));
    nextToken = res.nextToken;
  } while (nextToken);
  return items;
}

/** Throws the first GraphQL error of a mutation result, otherwise returns its data. */
export function unwrap<T>(res: { data?: T | null; errors?: { message: string }[] }): T {
  if (res.errors?.length) throw new Error(res.errors.map((e) => e.message).join('; '));
  return res.data as T;
}

/** Parses a.json() fields, which arrive either as objects or as JSON strings. */
export function parseJson<T>(value: unknown, fallback: T): T {
  let v = value;
  // Values can arrive JSON-encoded once or twice depending on how they were written.
  for (let i = 0; i < 3 && typeof v === 'string'; i++) {
    if (v === '') return fallback;
    try {
      v = JSON.parse(v);
    } catch {
      return fallback;
    }
  }
  return v == null ? fallback : (v as T);
}
